export function roundPoints(r, eventOk) {
  const pts = 40 + (r.profit > 0 ? 30 : 0) + (r.unsold === 0 ? 20 : 0) + Math.min(50, Math.max(0, Math.floor(r.profit / 40))) + (eventOk ? 30 : 0);
  return pts;
}

export function badges(history) {
  const rs = history.filter(Boolean).map((h) => h.result), out = [];
  if (rs.some((r) => r.profit >= 1000)) out.push('Первая тысяча');
  if (rs.some((r) => r.unsold === 0)) out.push('Без остатка');
  if (rs.some((r) => r.promoCost > 0 && r.extraSold > 0)) out.push('Реклама сработала');
  if (rs.length === 3) out.push('Три раунда пройдено');
  return out;
}

export function summary(history, events) {
  const done = history.filter(Boolean);
  const total = done.reduce((s, h) => s + roundPoints(h.result, events[h.round] === true), 0);
  const li = LEVELS.reduce((a, l, i) => (total >= l[0] ? i : a), 0);
  return { total, level: LEVELS[li][1], levelNo: li + 1, next: LEVELS[li + 1] || null, badges: badges(history) };
}
