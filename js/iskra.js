// Шаблонный наставник: принимает готовый результат и ничего не пересчитывает.
import { formatRub as R } from './calculations.js';
import { CONFIG } from './data.js';

const HIGH_PRICE = 500;

export function getFeedback(r) {
  if (r.profit < 0) {
    return {
      type: 'loss', title: 'Раунд закончился убытком',
      text: `Расходы (${R(r.expenses)}) оказались больше выручки (${R(r.revenue)}), убыток — ${R(-r.profit)}. Такое бывает: важно понять, какая часть расходов не успела окупиться.`,
      tip: r.unsold > 0
        ? `Закупленный товар продан не весь (осталось ${r.unsold} шт.). В следующий раз сравните закупку с ожидаемым спросом.`
        : 'Проверьте, не слишком ли велики расходы по сравнению с выручкой, и попробуйте изменить одно решение.',
    };
  }
  if (r.unsold > 0 && r.price >= HIGH_PRICE) {
    return {
      type: 'highPrice', title: 'Высокая цена снизила спрос',
      text: `При цене ${R(r.price)} модельный спрос — ${r.totalDemand} шт., а закуплено ${r.qty}. Не продано ${r.unsold} шт., и деньги остались в товаре.`,
      tip: 'Попробуйте цену чуть ниже или закупите меньше — сравните выручку и остаток товара.',
    };
  }
  if (r.unsold > 0) {
    return {
      type: 'unsold', title: 'Часть товара не продана',
      text: `Продано ${r.sold} из ${r.qty} шт., непроданных — ${r.unsold}. Они стоили ${R(r.unsold * r.unitCost)} закупки и пока не принесли выручки.`,
      tip: 'Перед закупкой сопоставьте количество с ожидаемым спросом, а не только с желанием продать больше.',
    };
  }
  if (r.promoCost > 0 && r.promoMargin < r.promoCost) {
    return {
      type: 'promoWaste', title: 'Продвижение не окупилось',
      text: `На продвижение потрачено ${R(r.promoCost)}, а дополнительные продажи (${r.extraSold} шт.) дали ${R(r.promoMargin)} наценки над закупкой. Затраты оказались больше отдачи.`,
      tip: 'Сравните бюджет рекламы с тем, сколько дополнительных единиц вы реально можете продать при вашем запасе товара.',
    };
  }
  if (r.promoCost > 0 && r.extraSold > 0) {
    return {
      type: 'promoWin', title: 'Продвижение увеличило продажи',
      text: `Благодаря продвижению продано на ${r.extraSold} шт. больше. Это дало ${R(r.promoMargin)} наценки при расходах на рекламу ${R(r.promoCost)}. Прибыль — ${R(r.profit)}.`,
      tip: 'Сравните этот вариант с другими бюджетами: больше рекламы не всегда значит больше прибыли.',
    };
  }
  if (r.profit > 0 && r.reserve >= CONFIG.reserveThreshold) {
    return {
      type: 'reserve', title: 'Вы сохранили денежный резерв',
      text: `Прибыль — ${R(r.profit)}, и до продаж у вас оставалось ${R(r.reserve)} свободных денег. Резерв помогает пережить неудачный период.`,
      tip: 'Оцените, можно ли часть резерва вложить в рост, не рискуя остаться без денег.',
    };
  }
  if (r.profit > 0) {
    return {
      type: 'profit', title: 'Есть положительная прибыль',
      text: `Выручка ${R(r.revenue)} покрыла расходы ${R(r.expenses)}, прибыль — ${R(r.profit)}. Весь закупленный товар продан.`,
      tip: 'Проверьте, не упустили ли вы продажи: возможно, спрос был выше закупки. Это не гарантия успеха, а повод проверить идею.',
    };
  }
  return {
    type: 'neutral', title: 'Результат около нуля',
    text: `Выручка (${R(r.revenue)}) равна расходам (${R(r.expenses)}). По одному раунду вывод делать рано.`,
    tip: 'Измените одно решение — цену, закупку или рекламу — и посмотрите, что изменится.',
  };
}
